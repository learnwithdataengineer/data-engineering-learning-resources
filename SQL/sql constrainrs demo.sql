USE COMPANY_DB;
 
DROP TABLE IF EXISTS DEPARTMENT;

CREATE TABLE DEPARTMENT (
    DEPT_ID INT PRIMARY KEY,
    DEPT_NAME VARCHAR(30) NOT NULL UNIQUE,
    LOCATION VARCHAR(30) DEFAULT 'HYDERABAD'
);

